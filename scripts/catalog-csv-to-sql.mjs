// Turns the Duke undergraduate bulletin's course export into a migration.
//
// 1. https://undergraduate.bulletins.duke.edu/courses → "Export all results as CSV"
// 2. Subject names (public, no token):
//    curl -o subjects.json https://streamer.oit.duke.edu/curriculum/list_of_values/fieldname/SUBJECT
// 3. node scripts/catalog-csv-to-sql.mjs courses.csv subjects.json > db/migrations/NNN_duke_catalog.sql
//
// The migration upserts on (subject, number), so ratings stay attached when
// titles change, and drops courses missing from the catalog only if nobody
// has rated or saved them.
import { readFileSync } from "node:fs";

const [csvPath, subjectsPath] = process.argv.slice(2);
if (!csvPath || !subjectsPath) {
  console.error("usage: node scripts/catalog-csv-to-sql.mjs courses.csv subjects.json");
  process.exit(1);
}

// RFC 4180: quoted fields may contain commas, quotes ("") and newlines.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += ch;
  }
  if (field || row.length) rows.push([...row, field]);
  return rows.filter((r) => r.some((f) => f.trim()));
}

const [header, ...records] = parseCsv(readFileSync(csvPath, "utf8").replace(/^﻿/, ""));
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`CSV is missing the "${name}" column (has: ${header.join(", ")})`);
  return i;
};
const SUBJECT = col("Subject code");
const NUMBER = col("Catalog Number");
const TITLE = col("Course Title");
const GRADING = col("Grading Basis");

const courses = new Map();
for (const r of records) {
  // AP / transfer-credit placeholders aren't courses anyone takes
  if (r[GRADING] === "Transfer Grading Basis") continue;
  const subject = r[SUBJECT].trim();
  const number = r[NUMBER].trim();
  const title = r[TITLE].trim().replace(/\s+/g, " ");
  if (!subject || !number || !title) continue;
  const key = `${subject} ${number}`;
  if (!courses.has(key)) courses.set(key, { subject, number, title });
}

const subjectNames = new Map(
  JSON.parse(readFileSync(subjectsPath, "utf8")).scc_lov_resp.lovs.lov.values.value.map((v) => [
    v.code.trim(),
    v.desc.trim(),
  ]),
);
const subjects = [...new Set([...courses.values()].map((c) => c.subject))].sort();

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = (items) => items.join(",\n");

const out = [];
out.push(`-- Duke undergraduate course catalog: ${courses.size} courses, ${subjects.length} subjects.
-- Generated by scripts/catalog-csv-to-sql.mjs from the undergraduate bulletin's
-- CSV export (${new Date().toISOString().slice(0, 10)}). Do not edit by hand.

create temp table catalog_import (subject text, number text, title text) on commit drop;
`);
out.push(`insert into subjects (code, name) values
${rows(subjects.map((s) => `  (${q(s)}, ${q(subjectNames.get(s) ?? s)})`))}
on conflict (code) do update set name = excluded.name;
`);
const all = [...courses.values()];
for (let i = 0; i < all.length; i += 1000) {
  out.push(`insert into catalog_import (subject, number, title) values
${rows(all.slice(i, i + 1000).map((c) => `  (${q(c.subject)}, ${q(c.number)}, ${q(c.title)})`))};
`);
}
out.push(`insert into courses (subject, number, title)
select subject, number, title from catalog_import
on conflict (subject, number) do update set title = excluded.title;

-- Remove courses that aren't in the catalog, unless someone rated or saved them.
delete from courses c
where not exists (select 1 from catalog_import i where i.subject = c.subject and i.number = c.number)
  and not exists (select 1 from ratings r where r.course_id = c.id)
  and not exists (select 1 from want_list w where w.course_id = c.id);

delete from subjects s where not exists (select 1 from courses c where c.subject = s.code);
`);

process.stdout.write(out.join("\n"));
console.error(`${courses.size} courses, ${subjects.length} subjects`);
